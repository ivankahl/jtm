//! `jtm lock` end to end.

#![allow(clippy::unwrap_used, clippy::panic)]

mod common;

use std::fs;
use std::path::Path;

use common::Fixture;
use serde_json::Value;

fn ready() -> Fixture {
    let f = Fixture::new(false);
    f.trust();
    f
}

fn json_in(f: &Fixture, dir: &Path, args: &[&str]) -> (i32, Value) {
    let output = f
        .jtm()
        .current_dir(dir)
        .arg("--json")
        .args(args)
        .output()
        .unwrap();
    let stdout = String::from_utf8(output.stdout).unwrap();
    assert_eq!(stdout.lines().count(), 1, "one envelope: {stdout}");
    (
        output.status.code().unwrap(),
        serde_json::from_str(&stdout).unwrap(),
    )
}

fn project(pin: &str) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    fs::write(
        dir.path().join(".jtm.toml"),
        format!("[tools]\ndemo = \"{pin}\"\n"),
    )
    .unwrap();
    fs::create_dir(dir.path().join("sub")).unwrap();
    dir
}

fn lock_text(dir: &Path) -> String {
    fs::read_to_string(dir.join("jtm.lock")).unwrap()
}

fn locked_version(dir: &Path) -> String {
    let value: toml::Value = toml::from_str(&lock_text(dir)).unwrap();
    value["tool"][0]["version"].as_str().unwrap().to_owned()
}

#[test]
fn lock_writes_every_platform_that_has_the_version() {
    let f = ready();
    let p = project("1.0");
    // Run from a subdirectory: the lock still goes next to .jtm.toml.
    let (code, value) = json_in(&f, &p.path().join("sub"), &["lock"]);
    assert_eq!(code, 0, "{value}");
    assert_eq!(value["command"], "lock");
    assert_eq!(value["changed"], true);
    let item = &value["data"]["tools"][0];
    assert_eq!(item["tool"], "demo");
    assert_eq!(item["version"], "1.0.0");
    assert_eq!(item["status"], "added");
    // The fixture publishes an index for the host platform only.
    assert_eq!(item["platforms"], serde_json::json!([f.platform]));

    let text = lock_text(p.path());
    assert!(
        text.starts_with("# jtm.lock — generated by jtm, do not edit\n"),
        "{text}"
    );
    let value: toml::Value = toml::from_str(&text).unwrap();
    assert_eq!(value["lock_version"].as_integer(), Some(1));
    let tool = &value["tool"][0];
    assert_eq!(tool["requested"].as_str(), Some("1.0"));
    assert_eq!(tool["pin_source"].as_str(), Some(".jtm.toml"));
    let artifact = &tool["artifact"][0];
    assert_eq!(artifact["platform"].as_str(), Some(f.platform.as_str()));
    assert_eq!(
        artifact["sha256"].as_str().unwrap(),
        jtm_security::sha256_hex(&common::archive("1.0.0"))
    );
    assert!(
        !text.contains(&f.home.path().display().to_string()),
        "no local paths"
    );
    let plugin = &value["plugin"][0];
    assert_eq!(plugin["name"].as_str(), Some("demo"));
    // The anchors of the compiled-in manifest, not the key the test trusts to re-sign.
    assert_eq!(
        plugin["signing_keys"][0].as_str(),
        Some(common::DEMO_ANCHOR)
    );

    // Stable: a second run changes nothing, byte for byte.
    let (code, again) = json_in(&f, p.path(), &["lock"]);
    assert_eq!(code, 0);
    assert_eq!(again["changed"], false);
    assert_eq!(again["data"]["tools"][0]["status"], "kept");
    assert_eq!(lock_text(p.path()), text);
}

#[test]
fn dry_run_writes_nothing() {
    let f = ready();
    let p = project("1.0");
    let (code, value) = json_in(&f, p.path(), &["lock", "--dry-run"]);
    assert_eq!(code, 0, "{value}");
    assert_eq!(value["data"]["dry_run"], true);
    assert_eq!(value["changed"], false);
    assert!(!p.path().join("jtm.lock").exists());
}

#[test]
fn locked_wins_over_newer_until_upgrade() {
    let f = ready();
    let p = project("1.0");
    json_in(&f, p.path(), &["lock"]);
    // Widen the pin: the locked 1.0.0 still satisfies `1`, so it is kept...
    fs::write(p.path().join(".jtm.toml"), "[tools]\ndemo = \"1\"\n").unwrap();
    let text = lock_text(p.path()).replace("requested = \"1.0\"", "requested = \"1\"");
    fs::write(p.path().join("jtm.lock"), text).unwrap();
    let (code, value) = json_in(&f, p.path(), &["lock"]);
    assert_eq!(code, 0, "{value}");
    assert_eq!(locked_version(p.path()), "1.0.0");
    // ...until --upgrade moves it forward.
    let (code, value) = json_in(&f, p.path(), &["lock", "--upgrade"]);
    assert_eq!(code, 0, "{value}");
    assert_eq!(value["data"]["tools"][0]["status"], "updated");
    assert_eq!(locked_version(p.path()), "1.1.0");
}

#[test]
fn a_changed_pin_is_re_resolved() {
    let f = ready();
    let p = project("1.0");
    json_in(&f, p.path(), &["lock"]);
    fs::write(p.path().join(".jtm.toml"), "[tools]\ndemo = \"1.1\"\n").unwrap();
    let (code, value) = json_in(&f, p.path(), &["lock"]);
    assert_eq!(code, 0, "{value}");
    assert_eq!(value["data"]["tools"][0]["status"], "updated");
    assert_eq!(locked_version(p.path()), "1.1.0");
}

#[test]
fn platform_narrows_the_lock() {
    let f = ready();
    let p = project("1.0");
    let other = if f.platform == "linux-x64" {
        "windows-x64"
    } else {
        "linux-x64"
    };
    let (code, value) = json_in(&f, p.path(), &["lock", "--platform", other]);
    assert_eq!(code, 0, "{value}");
    assert_eq!(
        value["data"]["tools"][0]["platforms"],
        serde_json::json!([])
    );
    let (code, value) = json_in(&f, p.path(), &["lock", "--platform", "amiga"]);
    assert_eq!(code, 2, "{value}");
}

#[test]
fn no_pins_means_nothing_to_lock() {
    let f = ready();
    let dir = tempfile::tempdir().unwrap();
    let (code, value) = json_in(&f, dir.path(), &["lock"]);
    assert_eq!(code, 2, "{value}");
    assert!(
        value["error"]["message"]
            .as_str()
            .unwrap()
            .contains("jtm pin")
    );
}
