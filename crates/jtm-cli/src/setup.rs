/// Warning code for a shell hook `self setup` could not add.
pub(crate) const W_SHELL_HOOK_SKIPPED: &str = "W_SHELL_HOOK_SKIPPED";

const START: &str = "# >>> jtm >>>";
const END: &str = "# <<< jtm <<<";

/// What the user environment should hold: the current links' bin directories and the `[env]`
/// variables pointing at the links.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct SetupPlan {
    pub(crate) path: Vec<PathBuf>,
    pub(crate) vars: Vec<(String, String)>,
}

/// The plan for every tool with a default and a current link.
pub(crate) fn plan(session: &Session<'_>) -> Result<SetupPlan> {
    let defaults = jtm_core::activate::Defaults::load(&session.dirs().defaults_file())?;
    let mut plan = SetupPlan::default();
    for (tool, _) in defaults.iter() {
        let link = session.current_link(tool);
        if links::read(&link).is_none() {
            continue;
        }
        let Ok(plugin) = session.plugin(tool) else {
            continue;
        };
        let env = tool_env(&plugin.manifest, &link);
        plan.path.extend(env.path);
        plan.vars.extend(env.vars);
    }
    Ok(plan)
}

/// `<data>/env.sh`: puts each bin directory first on `PATH` once and exports the variables.
pub(crate) fn env_sh(plan: &SetupPlan) -> String {
    let mut out =
        String::from("# Generated by jtm; `jtm default` and `jtm self setup` rewrite it.\n");
    for dir in plan.path.iter().rev() {
        let dir = posix_quote(&dir.display().to_string());
        out.push_str(&format!(
            "case \":${{PATH}}:\" in\n  *:{dir}:*) ;;\n  *) PATH={dir}:\"$PATH\" ;;\nesac\n"
        ));
    }
    out.push_str("export PATH\n");
    for (name, value) in &plan.vars {
        out.push_str(&format!("export {name}={}\n", posix_quote(value)));
    }
    out
}

/// `<data>/env.fish`, the same for fish.
pub(crate) fn env_fish(plan: &SetupPlan) -> String {
    let mut out =
        String::from("# Generated by jtm; `jtm default` and `jtm self setup` rewrite it.\n");
    for dir in plan.path.iter().rev() {
        let dir = fish_quote(&dir.display().to_string());
        out.push_str(&format!(
            "contains -- {dir} $PATH; or set -gx PATH {dir} $PATH\n"
        ));
    }
    for (name, value) in &plan.vars {
        out.push_str(&format!("set -gx {name} {}\n", fish_quote(value)));
    }
    out
}

/// The marked block for an rc file of `shell` (`None` for a plain POSIX `.profile`): it sources
/// `env_file` and, given `hook`, the path of jtm, loads the shell hook. For PowerShell, whose
/// environment lives in the registry, `env_file` is `None` and only the hook is loaded.
pub(crate) fn rc_block(
    env_file: Option<&Path>,
    shell: Option<Shell>,
    hook: Option<&str>,
) -> String {
    let mut lines = Vec::new();
    if let Some(env_file) = env_file {
        let file = env_file.display().to_string();
        lines.push(if shell == Some(Shell::Fish) {
            let file = fish_quote(&file);
            format!("test -f {file}; and source {file}")
        } else {
            let file = posix_quote(&file);
            format!("[ -f {file} ] && . {file}")
        });
    }
    if let Some(exe) = hook {
        match shell {
            Some(Shell::Bash | Shell::Zsh) => {
                let name = shell.map_or("bash", Shell::name);
                let exe = posix_quote(exe);
                lines.push(format!(
                    "[ -x {exe} ] && eval \"$({exe} shell-init {name})\""
                ));
            }
            Some(Shell::Fish) => {
                let exe = fish_quote(exe);
                lines.push(format!(
                    "status is-interactive; and test -x {exe}; and {exe} shell-init fish | source"
                ));
            }
            Some(Shell::Pwsh) => {
                let exe = pwsh_quote(exe);
                lines.push(format!(
                    "if (Test-Path -LiteralPath {exe}) {{ Invoke-Expression ((& {exe} shell-init \
                     pwsh) -join \"`n\") }}"
                ));
            }
            Some(Shell::Cmd) | None => {}
        }
    }
    let what = match (
        env_file.is_some(),
        lines.len() > usize::from(env_file.is_some()),
    ) {
        (true, true) => "puts default tool versions on PATH and applies project pins on cd",
        (true, false) => "puts default tool versions on PATH",
        (false, _) => "applies project pins on cd",
    };
    format!(
        "{START}\n# Added by `jtm self setup`: {what}.\n{}\n{END}\n",
        lines.join("\n")
    )
}

/// The rc file's new text with `block` in place of an earlier jtm block, or appended. `None`
/// when the file already holds exactly this block.
pub(crate) fn update_rc(existing: Option<&str>, block: &str) -> Option<String> {
    let Some(existing) = existing else {
        return Some(block.to_owned());
    };
    let updated = match (existing.find(START), existing.find(END)) {
        (Some(start), Some(end)) if start < end => {
            let mut tail = end + END.len();
            if existing[tail..].starts_with('\n') {
                tail += 1;
            }
            format!("{}{block}{}", &existing[..start], &existing[tail..])
        }
        _ => {
            let mut text = existing.to_owned();
            if !text.is_empty() {
                if !text.ends_with('\n') {
                    text.push('\n');
                }
                text.push('\n');
            }
            text.push_str(block);
            text
        }
    };
    (updated != existing).then_some(updated)
}

/// The rc file for the user's login shell, and the shell it is for: `None` for a shell jtm has
/// no hook for, whose `.profile` gets the environment only.
pub(crate) fn rc_file(
    home: &Path,
    os: Os,
    env: &dyn Fn(&str) -> Option<String>,
) -> (PathBuf, Option<Shell>) {
    let shell = env("SHELL").unwrap_or_default();
    let name = shell.rsplit('/').next().unwrap_or_default();
    match name {
        "zsh" => {
            let dir = env("ZDOTDIR")
                .filter(|d| d.starts_with('/'))
                .map_or_else(|| home.to_path_buf(), PathBuf::from);
            (dir.join(".zshrc"), Some(Shell::Zsh))
        }
        "bash" if os == Os::Macos => (home.join(".bash_profile"), Some(Shell::Bash)),
        "bash" => (home.join(".bashrc"), Some(Shell::Bash)),
        "fish" => {
            let config = env("XDG_CONFIG_HOME")
                .filter(|d| d.starts_with('/'))
                .map_or_else(|| home.join(".config"), PathBuf::from);
            (
                config.join("fish").join("conf.d").join("jtm.fish"),
                Some(Shell::Fish),
            )
        }
        _ => (home.join(".profile"), None),
    }
}

/// The PowerShell profile for the current user and host, as PowerShell itself reports it, so a
/// Documents folder moved by OneDrive is honoured. Tries PowerShell 7, then Windows PowerShell.
fn powershell_profile() -> Option<PathBuf> {
    ["pwsh", "powershell"].iter().find_map(|shell| {
        let output = std::process::Command::new(shell)
            .args([
                "-NoProfile",
                "-NonInteractive",
                "-Command",
                "$PROFILE.CurrentUserCurrentHost",
            ])
            .stdin(std::process::Stdio::null())
            .output()
            .ok()
            .filter(|o| o.status.success())?;
        let path = String::from_utf8_lossy(&output.stdout).trim().to_owned();
        (!path.is_empty()).then(|| PathBuf::from(path))
    })
}

/// Prepends the entries of `add` missing from the `;`-separated `existing`, comparing
/// case-insensitively and ignoring a trailing separator. `None` when nothing is missing.
#[cfg_attr(not(windows), allow(dead_code))]
pub(crate) fn merge_path(existing: &str, add: &[String]) -> Option<String> {
    let norm = |entry: &str| entry.trim_end_matches(['\\', '/']).to_lowercase();
    let present: Vec<String> = existing
        .split(';')
        .filter(|e| !e.is_empty())
        .map(norm)
        .collect();
    let missing: Vec<&String> = add.iter().filter(|a| !present.contains(&norm(a))).collect();
    if missing.is_empty() {
        return None;
    }
    let mut entries: Vec<&str> = missing.iter().map(|s| s.as_str()).collect();
    entries.extend(existing.split(';').filter(|e| !e.is_empty()));
    Some(entries.join(";"))
}

/// Removes the entries of `remove` from the `;`-separated `existing`, compared as in
/// [`merge_path`]. `None` when none is present.
#[cfg_attr(not(windows), allow(dead_code))]
pub(crate) fn prune_path(existing: &str, remove: &[String]) -> Option<String> {
    let norm = |entry: &str| entry.trim_end_matches(['\\', '/']).to_lowercase();
    let remove: Vec<String> = remove.iter().map(|r| norm(r)).collect();
    let entries: Vec<&str> = existing.split(';').filter(|e| !e.is_empty()).collect();
    let kept: Vec<&str> = entries
        .iter()
        .copied()
        .filter(|e| !remove.contains(&norm(e)))
        .collect();
    (kept.len() != entries.len()).then(|| kept.join(";"))
}

/// One file or setting `self setup` changed, or with `--dry-run` would change.
#[derive(Debug, Serialize)]
pub(crate) struct Target {
    pub(crate) path: String,
    pub(crate) changed: bool,
}

#[derive(Debug, Serialize)]
pub(crate) struct SetupData {
    dry_run: bool,
    /// Whether the block loads the shell hook.
    hook: bool,
    path: Vec<String>,
    vars: std::collections::BTreeMap<String, String>,
    targets: Vec<Target>,
}

impl Human for SetupData {
    fn render_human(&self, out: &mut dyn Write) -> io::Result<()> {
        for target in &self.targets {
            let verb = match (target.changed, self.dry_run) {
                (false, _) => "unchanged",
                (true, true) => "would update",
                (true, false) => "updated",
            };
            writeln!(out, "{verb} {}", target.path)?;
        }
        if self.targets.iter().any(|t| t.changed) && !self.dry_run {
            writeln!(out, "open a new terminal to pick up the changes")?;
        }
        Ok(())
    }
}

/// Writes jtm's env files from the current defaults. `jtm default` calls this so a new default
/// reaches new shells without touching any rc file again.
pub(crate) fn refresh(session: &Session<'_>) -> Result<Vec<Target>> {
    let plan = plan(session)?;
    let mut targets = Vec::new();
    #[cfg(not(windows))]
    for (name, text) in [("env.sh", env_sh(&plan)), ("env.fish", env_fish(&plan))] {
        let path = session.dirs().data.join(name);
        let changed = write_if_changed(&path, &text, false)?;
        targets.push(Target {
            path: path.display().to_string(),
            changed,
        });
    }
    #[cfg(windows)]
    if let Some(previous) = applied(session)? {
        targets.extend(windows::apply(&plan, &previous, false)?);
        record(session, &plan)?;
    }
    Ok(targets)
}

/// The file `self setup` leaves in `<data>/state`, so `jtm default` knows to keep the user
/// environment current. It holds the plan last applied, so a later run can remove variables
/// and `PATH` entries for defaults that are gone.
#[cfg_attr(not(windows), allow(dead_code))]
const SETUP_MARKER: &str = "user-env";

/// The plan last applied by `self setup`, or `None` when it never ran. A marker from an older
/// jtm, which is empty, reads as an empty plan.
#[cfg_attr(not(windows), allow(dead_code))]
fn applied(session: &Session<'_>) -> Result<Option<SetupPlan>> {
    let marker = session.dirs().state().join(SETUP_MARKER);
    Ok(read_existing(&marker)?.map(|text| serde_json::from_str(&text).unwrap_or_default()))
}

/// Records `plan` as the one applied.
fn record(session: &Session<'_>, plan: &SetupPlan) -> Result<()> {
    let text = serde_json::to_string(plan).unwrap_or_default();
    write_if_changed(&session.dirs().state().join(SETUP_MARKER), &text, false)?;
    Ok(())
}

/// The text of `path`, or `None` when it does not exist. Any other failure, such as a file
/// that is not UTF-8, is an error: treating it as missing would overwrite the user's file.
pub(crate) fn read_existing(path: &Path) -> Result<Option<String>> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(JtmError::io(path, e)),
    }
}

/// Writes `text` to `path` unless it already holds it. Returns whether it differed.
fn write_if_changed(path: &Path, text: &str, dry_run: bool) -> Result<bool> {
    let existing = read_existing(path)?;
    if existing.as_deref() == Some(text) {
        return Ok(false);
    }
    if !dry_run {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| JtmError::io(dir, e))?;
        }
        std::fs::write(path, text).map_err(|e| JtmError::io(path, e))?;
    }
    Ok(true)
}

/// Options for [`setup`].
#[derive(Debug, Clone, Copy)]
pub(crate) struct SetupOptions {
    pub(crate) dry_run: bool,
    /// Leave the shell hook out of the rc block.
    pub(crate) no_hook: bool,
}

pub(crate) fn setup(ctx: &Context, options: SetupOptions) -> Result<Outcome<SetupData>> {
    let dry_run = options.dry_run;
    let session = Session::open(ctx)?;
    let plan = plan(&session)?;
    let exe = (!options.no_hook).then(jtm_exe);
    let mut targets = Vec::new();
    let mut warnings = Vec::new();
    let mut hook = false;
    let os = session.platform().os();
    if os == Os::Windows {
        #[cfg(windows)]
        {
            let previous = applied(&session)?.unwrap_or_default();
            targets.extend(windows::apply(&plan, &previous, dry_run)?);
        }
        match (powershell_profile(), exe.as_deref()) {
            (Some(profile), Some(exe)) => {
                let block = rc_block(None, Some(Shell::Pwsh), Some(exe));
                // Windows PowerShell reads a file without a byte order mark as the ANSI code
                // page, so a new profile gets one for a non-ASCII jtm path.
                targets.push(edit_rc(ctx, &profile, &block, "\u{feff}", dry_run)?);
                hook = true;
            }
            // With --no-hook the profile holds nothing for jtm, so an earlier block goes.
            (Some(profile), None) => {
                if read_existing(&profile)?.is_some_and(|text| text.contains(START)) {
                    targets.push(edit_rc(ctx, &profile, "", "", dry_run)?);
                }
            }
            (None, Some(_)) => warnings.push(Warning {
                code: W_SHELL_HOOK_SKIPPED,
                message: "no PowerShell was found, so the shell hook was not added; add \
                          `Invoke-Expression ((& jtm shell-init pwsh) -join \"`n\")` to your \
                          profile"
                    .to_owned(),
                details: serde_json::Map::new(),
            }),
            (None, None) => {}
        }
    } else {
        for (name, text) in [("env.sh", env_sh(&plan)), ("env.fish", env_fish(&plan))] {
            let path = session.dirs().data.join(name);
            let changed = write_if_changed(&path, &text, dry_run)?;
            targets.push(Target {
                path: path.display().to_string(),
                changed,
            });
        }
        let home = std::env::var("HOME")
            .ok()
            .filter(|h| h.starts_with('/'))
            .ok_or_else(|| JtmError::usage("HOME is not set, so jtm cannot find your rc file"))?;
        let (rc, shell) = rc_file(Path::new(&home), os, &|key| std::env::var(key).ok());
        let env_file = session.dirs().data.join(if shell == Some(Shell::Fish) {
            "env.fish"
        } else {
            "env.sh"
        });
        if shell.is_none() && exe.is_some() {
            warnings.push(Warning {
                code: W_SHELL_HOOK_SKIPPED,
                message: format!(
                    "jtm has no shell hook for your login shell, so {} only puts default \
                     versions on PATH; use bash, zsh, fish or pwsh for project pins on cd",
                    rc.display()
                ),
                details: serde_json::Map::new(),
            });
        }
        hook = exe.is_some() && shell.is_some();
        let block = rc_block(Some(&env_file), shell, exe.as_deref());
        targets.push(edit_rc(ctx, &rc, &block, "", dry_run)?);
    }
    if !dry_run {
        record(&session, &plan)?;
    }
    Ok(Outcome {
        command: "self setup",
        changed: !dry_run && targets.iter().any(|t| t.changed),
        data: SetupData {
            dry_run,
            hook,
            path: plan.path.iter().map(|p| p.display().to_string()).collect(),
            vars: plan.vars.into_iter().collect(),
            targets,
        },
        warnings,
    })
}

/// Puts `block` into the rc file `rc` after confirmation or with `--yes`, keeping the rest of
/// the file; an empty `block` removes jtm's. A new file starts with `prefix`.
fn edit_rc(ctx: &Context, rc: &Path, block: &str, prefix: &str, dry_run: bool) -> Result<Target> {
    let existing = read_existing(rc)?;
    let update = match &existing {
        Some(text) => update_rc(Some(text), block),
        None => Some(format!("{prefix}{block}")),
    };
    if let Some(text) = &update
        && !dry_run
    {
        let question = if block.is_empty() {
            format!("Remove the jtm block from {}?", rc.display())
        } else {
            format!("Add these lines to {}?\n\n{block}", rc.display())
        };
        if !confirm(ctx, &question)? {
            return Err(JtmError::InputRequired {
                action: format!("adding the jtm block to {}", rc.display()),
                resolve: "--yes".to_owned(),
            });
        }
        write_if_changed(rc, text, false)?;
    }
    Ok(Target {
        path: rc.display().to_string(),
        changed: update.is_some(),
    })
}

