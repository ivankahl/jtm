//! `jtm.lock` (SPEC.md section 11): the exact version, URL and SHA-256 per tool and platform,
//! and the identity of every plugin used, so every machine installs byte-identical toolchains.
//!
//! Rendering is deterministic: plugins and tools are sorted by name and artifacts by platform,
//! so the same lock always produces the same bytes and diffs stay small. The file holds URLs
//! and hashes only, never paths on the machine that wrote it.

use std::fs;
use std::io;
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::error::{JtmError, Result};
use crate::platform::Platform;

/// The lockfile's name, next to the project's `.jtm.toml`.
pub const LOCK_FILE: &str = "jtm.lock";

/// The only lockfile format this build reads and writes.
pub const LOCK_VERSION: u32 = 1;

const HEADER: &str = "# jtm.lock — generated by jtm, do not edit\n";

/// A parsed `jtm.lock`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Lockfile {
    pub generated_by: String,
    pub plugins: Vec<LockedPlugin>,
    pub tools: Vec<LockedTool>,
}

/// The identity of a plugin a locked tool came from.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedPlugin {
    pub name: String,
    /// `builtin`, or where the plugin came from.
    pub source: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rev: Option<String>,
    pub manifest_sha256: String,
    pub signing_keys: Vec<String>,
}

/// One locked tool.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedTool {
    pub name: String,
    /// The pin as written, such as `temurin:21`.
    pub requested: String,
    /// The pin file, relative to the lockfile's directory with `/` separators.
    pub pin_source: String,
    pub variant: String,
    pub version: String,
    #[serde(rename = "artifact", default)]
    pub artifacts: Vec<LockedArtifact>,
}

/// One locked archive for one platform.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedArtifact {
    pub platform: String,
    pub url: String,
    pub size: u64,
    pub sha256: String,
}

impl LockedTool {
    pub fn artifact(&self, platform: &str) -> Option<&LockedArtifact> {
        self.artifacts.iter().find(|a| a.platform == platform)
    }
}

/// The file layout, in the order the spec shows it.
#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct File {
    lock_version: u32,
    generated_by: String,
    #[serde(rename = "plugin", default)]
    plugins: Vec<LockedPlugin>,
    #[serde(rename = "tool", default)]
    tools: Vec<LockedTool>,
}

impl Lockfile {
    /// An empty lockfile written by this jtm.
    pub fn new() -> Lockfile {
        Lockfile {
            generated_by: format!("jtm {}", env!("CARGO_PKG_VERSION")),
            plugins: Vec::new(),
            tools: Vec::new(),
        }
    }

    /// Parses and checks `text`, the contents of the lockfile at `path`. Anything it cannot
    /// read is `E_LOCK_OUTDATED`: `jtm lock` writes a fresh one.
    pub fn parse(path: &Path, text: &str) -> Result<Lockfile> {
        let outdated = |message: String| JtmError::LockOutdated {
            message: format!(
                "{} cannot be read: {message}; run `jtm lock` to write it again",
                path.display()
            ),
        };
        let file: File = toml::from_str(text).map_err(|e| outdated(e.message().to_owned()))?;
        if file.lock_version != LOCK_VERSION {
            return Err(outdated(format!(
                "lock_version {} is not supported; this jtm writes {LOCK_VERSION}",
                file.lock_version
            )));
        }
        for tool in &file.tools {
            for artifact in &tool.artifacts {
                if artifact.platform.parse::<Platform>().is_err() {
                    return Err(outdated(format!(
                        "`{}` has an artifact for unknown platform `{}`",
                        tool.name, artifact.platform
                    )));
                }
                if !is_sha256(&artifact.sha256) {
                    return Err(outdated(format!(
                        "`{}` for {} has an invalid sha256",
                        tool.name, artifact.platform
                    )));
                }
            }
        }
        Ok(Lockfile {
            generated_by: file.generated_by,
            plugins: file.plugins,
            tools: file.tools,
        })
    }

    /// Reads `dir/jtm.lock`, or `None` when there is none.
    pub fn read(dir: &Path) -> Result<Option<Lockfile>> {
        let path = dir.join(LOCK_FILE);
        match fs::read_to_string(&path) {
            Ok(text) => Lockfile::parse(&path, &text).map(Some),
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(JtmError::io(&path, e)),
        }
    }

    pub fn tool(&self, name: &str) -> Option<&LockedTool> {
        self.tools.iter().find(|t| t.name == name)
    }

    /// The file's text: sorted by plugin, tool and platform.
    pub fn render(&self) -> String {
        let mut plugins = self.plugins.clone();
        plugins.sort_by(|a, b| a.name.cmp(&b.name));
        let mut tools = self.tools.clone();
        tools.sort_by(|a, b| a.name.cmp(&b.name));
        for tool in &mut tools {
            tool.artifacts.sort_by(|a, b| a.platform.cmp(&b.platform));
        }
        let file = File {
            lock_version: LOCK_VERSION,
            generated_by: self.generated_by.clone(),
            plugins,
            tools,
        };
        let body = toml::to_string(&file).unwrap_or_default();
        format!("{HEADER}{body}")
    }

    /// Writes `dir/jtm.lock` atomically.
    pub fn write(&self, dir: &Path) -> Result<()> {
        crate::project::write_atomic(&dir.join(LOCK_FILE), self.render().as_bytes())
    }
}

impl Default for Lockfile {
    fn default() -> Self {
        Lockfile::new()
    }
}

fn is_sha256(text: &str) -> bool {
    text.len() == 64
        && text
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

